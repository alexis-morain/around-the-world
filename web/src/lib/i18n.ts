/** Préfixe d'URL d'une langue, base du site comprise. */
export function href(lang: Lang, path = ""): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, "");
  const p = path.replace(/^\//, "");
  return `${base}/${lang === "en" ? "en/" : ""}${p}`;
}
